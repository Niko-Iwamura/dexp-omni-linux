/* 0 = offered by the Windows app, 1 = alternate/legacy ID it hides,
 * 2 = fed by the Windows app (audio wave / shadow) */
int omni_mode_kind(unsigned m)
{
    if (m == 29 || m == 30) return 2;
    if ((m >= 1 && m <= 18) || m == 20) return 0;
    return 1;
}

/* IDs a user can pick without the Windows app, in the app's order */
int omni_selectable_modes(uint8_t out[32])
{
    int n = 0;
    unsigned m;
    for (m = 0; m <= 30; m++)
        if (omni_mode_kind(m) == 0)
            out[n++] = (uint8_t)m;
    return n;
}

