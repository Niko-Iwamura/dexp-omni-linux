#!/usr/bin/env python3
"""Generate src/omni_layout.c — exact key geometry extracted from the
Windows configurator skin (Skin/XML/DeviceXml/keyboarddevice.xml inside
the extracted OMNI.exe installation).

Each <DeviceKeyButton> in the DuiLib XML carries the pixel position and size
of one key on the 673x218 keyboard image, plus the LED-image index (which
matches the per-LED table read via cmd 0x1B).

Usage: point XML at your extracted driver copy and run:
    python3 tools/gen_layout.py
"""
import os
import re
import sys

XML = os.environ.get(
    "OMNI_SKIN_XML",
    "keyboarddevice.xml",  # path to the skin XML (see README)
)

HIDDEN_STRIP = [120, 121, 122, 123, 124,   # M1..M5
                111,                        # App
                125,                        # RWin
                13, 14, 15, 16, 17,        # PrintScreen..Media-2
                35, 36, 57,                 # Insert Home End
                62,                         # NonUS #
                79, 80, 81, 82, 83,        # OEM extra keys
                100, 101, 102, 103]         # OEM extra keys


def main():
    xml = open(XML, encoding="utf-8").read()
    btns = re.findall(r"<DeviceKeyButton\b[^>]*>", xml)
    if len(btns) != 126:
        print(f"warning: expected 126 DeviceKeyButton, got {len(btns)}", file=sys.stderr)

    boxes = {}
    for b in btns:
        def g(a, d=""):
            m = re.search(a + r'="([^"]*)"', b)
            return m.group(1) if m else d
        name = g("name")
        idx = int(name.split("_")[1])
        pos = g("pos", "0,0,0,0").split(",")
        x, y = int(pos[0]), int(pos[1])
        w, h = int(g("width", "0")), int(g("height", "0"))
        if x > 1 and y > 1 and w > 1 and h > 1:
            boxes[idx] = (x, y, w, h)

    out = []
    out.append("/*")
    out.append(" * omni_layout.c — key geometry for the GUI keyboard view.")
    out.append(" *")
    out.append(" * GENERATED by scripts/gen_layout.py from the original Windows")
    out.append(" * configurator skin (Skin/XML/DeviceXml/keyboarddevice.xml).")
    out.append(" * Canvas: 673 x 218 logical pixels. Keys not present on the skin")
    out.append(" * image (macro keys M1-M5, media row, etc.) are listed in")
    out.append(" * omni_hidden_keys[] and rendered as a strip below the canvas.")
    out.append(" */")
    out.append('#include "omni.h"')
    out.append("")
    out.append("const struct omni_key_box omni_key_boxes[] = {")
    for idx in sorted(boxes):
        x, y, w, h = boxes[idx]
        out.append(f"    {{ {idx:3d}, {x:3d}, {y:3d}, {w:3d}, {h:3d} }},")
    out.append("};")
    out.append(f"const int omni_key_box_count = {len(boxes)};")
    out.append("")
    out.append("const int omni_hidden_keys[] = {")
    line = "   "
    for k in HIDDEN_STRIP:
        line += f" {k},"
        if len(line) > 70:
            out.append(line)
            line = "   "
    if line.strip():
        out.append(line)
    out.append("};")
    out.append(f"const int omni_hidden_key_count = {len(HIDDEN_STRIP)};")
    out.append("")
    out_path = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                            "..", "src", "omni_layout.c")
    open(out_path, "w").write("\n".join(out) + "\n")
    print(f"boxes: {len(boxes)}, hidden strip: {len(HIDDEN_STRIP)}, total {len(boxes)+len(HIDDEN_STRIP)} of 126")


if __name__ == "__main__":
    main()
